# ==============================
# 15 数据容器：dict字典
# ==============================


# 一、创建字典

dict1 = {
    "张三": 80,
    "李四": 90,
    "王五": 95
}

print(dict1)


# ==============================
# 二、根据key获取value
# ==============================

print(dict1["张三"])
print(dict1["李四"])


# ==============================
# 三、修改value
# ==============================

dict1["张三"] = 100

print(dict1)


# ==============================
# 四、添加键值对
# ==============================

dict1["赵六"] = 88

print(dict1)


# ==============================
# 五、删除键值对
# pop()
# ==============================

dict1.pop("赵六")

print(dict1)


# ==============================
# 六、获取所有key
# keys()
# ==============================

dict1 = {
    "张三": 80,
    "李四": 90,
    "王五": 95
}

print(dict1.keys())


# ==============================
# 七、获取所有value
# values()
# ==============================

print(dict1.values())


# ==============================
# 八、获取所有键值对
# items()
# ==============================

print(dict1.items())


# ==============================
# 九、遍历key
# ==============================

for i in dict1.keys():
    print(i)


# ==============================
# 十、遍历value
# ==============================

for i in dict1.values():
    print(i)


# ==============================
# 十一、遍历键值对
# ==============================

for item in dict1.items():
    print(item)


# ==============================
# 十二、分别获取key和value
# ==============================

for item in dict1.items():

    print(item[0])
    print(item[1])


# ==============================
# 十三、使用两个变量接收key和value
# ==============================

for key, value in dict1.items():

    print("姓名:", key)
    print("成绩:", value)


# ==============================
# 十四、判断key是否存在
# ==============================

if "张三" in dict1:
    print("张三存在")


# ==============================
# 十五、清空字典
# ==============================

dict1.clear()

print(dict1)


# ==============================
# 十六、嵌套字典
# ==============================

student = {
    "张三": {
        "年龄": 18,
        "成绩": 90
    },

    "李四": {
        "年龄": 19,
        "成绩": 95
    }
}

print(student)


# ==============================
# 十七、获取嵌套字典
# ==============================

print(student["张三"]["年龄"])
print(student["张三"]["成绩"])


# ==============================
# 十八、遍历嵌套字典
# ==============================

for name, info in student.items():

    print("姓名:", name)
    print("年龄:", info["年龄"])
    print("成绩:", info["成绩"])


# ==============================
# 十九、购物车案例
# ==============================

cart = {}

cart["苹果"] = {
    "价格": 5,
    "数量": 3
}

cart["香蕉"] = {
    "价格": 4,
    "数量": 2
}

print(cart)


# ==============================
# 二十、遍历购物车
# ==============================

for name, info in cart.items():

    print("商品:", name)
    print("价格:", info["价格"])
    print("数量:", info["数量"])


# ==============================
# 二十一、计算购物车总价
# ==============================

total = 0

for name, info in cart.items():

    total = total + info["价格"] * info["数量"]

print("购物车总价:", total)