# 整型 int - 整数
age = 25
count = -10
big_num = 9999999999
print(type(age))    # <class 'int'>

# 浮点型 float - 小数
price = 99.9
pi = 3.14159
score = 88.0
print(type(price))  # <class 'float'>

# 布尔型 bool - 只有 True 和 False
is_student = True
is_online = False
print(type(is_student))  # <class 'bool'>

# 复数 complex（了解即可）
z = 3 + 4j
print(type(z))      # <class 'complex'>