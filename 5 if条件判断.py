# 1. 单分支 - if
age = 18
if age >= 18:
    print("你已经成年了")

# 2. 双分支 - if...else
score = 85
if score >= 60:
    print("及格了！")
else:
    print("不及格，继续努力！")

# 3. 多分支 - if...elif...else
score = 75
if score >= 90:
    print("优秀")
elif score >= 80:
    print("良好")
elif score >= 60:
    print("及格")
else:
    print("不及格")