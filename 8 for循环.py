# 08 for循环

# 一、for循环基础
# for循环可以依次取出数据中的每一个元素

name = "张三"

for i in name:
    print(i)


# ==============================
# 二、for循环遍历列表
# ==============================

list1 = [10, 20, 30, 40, 50]

for i in list1:
    print(i)


# ==============================
# 三、range()基础
# ==============================

# range(5)表示0到4

for i in range(5):
    print(i)


# ==============================
# 四、range()指定开始和结束
# ==============================

# 包含开始，不包含结束
# range(1, 6) -> 1 2 3 4 5

for i in range(1, 6):
    print(i)


# ==============================
# 五、range()指定步长
# ==============================

# 第三个参数表示每次增加多少

for i in range(1, 11, 2):
    print(i)

# 结果：
# 1
# 3
# 5
# 7
# 9


# ==============================
# 六、倒序
# ==============================

for i in range(10, 0, -1):
    print(i)


# ==============================
# 七、计算1到100的和
# ==============================

sum1 = 0

for i in range(1, 101):
    sum1 = sum1 + i

print("1到100的和:", sum1)


# ==============================
# 八、计算1到100之间的偶数
# ==============================

for i in range(1, 101):
    if i % 2 == 0:
        print(i)


# ==============================
# 九、计算1到100之间偶数的和
# ==============================

sum2 = 0

for i in range(1, 101):
    if i % 2 == 0:
        sum2 = sum2 + i

print("偶数和:", sum2)


# ==============================
# 十、统计列表中的及格人数
# ==============================

score = [78, 56, 92, 43, 65, 89, 51, 37, 74, 60]

pass_count = 0

for i in score:
    if i >= 60:
        pass_count = pass_count + 1

print("及格人数:", pass_count)


# ==============================
# 十一、统计不及格人数
# ==============================

fail_count = 0

for i in score:
    if i < 60:
        fail_count = fail_count + 1

print("不及格人数:", fail_count)


# ==============================
# 十二、找出列表中的正数
# ==============================

num_list = [-5, 10, -2, 8, 0, 6, -9]

for i in num_list:
    if i > 0:
        print(i)


# ==============================
# 十三、for循环 + input()
# 输入10个成绩
# ==============================

score_list = []

for i in range(10):
    cj = float(input("请输入第" + str(i + 1) + "名学生的成绩: "))
    score_list.append(cj)

print("所有成绩:", score_list)


# ==============================
# 十四、嵌套for循环
# ==============================

for i in range(1, 4):
    for j in range(1, 4):
        print("i =", i, "j =", j)


# ==============================
# 十五、打印三角形
# ==============================

for i in range(1, 6):
    for j in range(i):
        print("*", end="")
    print()


# 结果：
# *
# **
# ***
# ****
# *****


# ==============================
# 十六、九九乘法表
# ==============================

for i in range(1, 10):
    for j in range(1, i + 1):
        print(f"{j} × {i} = {i * j}", end="    ")
    print()


# ==============================
# 十七、for循环综合案例
# ==============================

score = [78, 56, 92, 43, 65, 89, 51, 37, 74, 60]

max_score = score[0]
min_score = score[0]
sum_score = 0

for i in score:

    if i > max_score:
        max_score = i

    if i < min_score:
        min_score = i

    sum_score = sum_score + i

avg_score = sum_score / len(score)

print("最高分:", max_score)
print("最低分:", min_score)
print("平均分:", avg_score)